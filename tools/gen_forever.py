#!/usr/bin/env python3
"""Generate RareNet/ForeverRares.lua from wow-raredb (data from ForeverChanges,
foreverchanges.pro, used with their permission; credit them wherever it shows).

ns.ForeverRares = { [npc] = { name, level, tameable, uiMapID, { x, y, ... } } }
ns.ForeverDrops = { [npc] = { itemID, quality, ... } }
"""
import json
import os
import re
import sqlite3
import sys
from urllib.parse import urlparse

DB = sys.argv[1] if len(sys.argv) > 1 else "../wow-raredb/raredb.sqlite"
CURATED = "data/curated_rares.json"
ZONES = "../wow-copilot/data/zones.json"
OUT = "RareNet/ForeverRares.lua"

con = sqlite3.connect(DB)


def lua_string(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def first_int(text):
    m = re.search(r"\d+", text or "")
    return int(m.group()) if m else 0


def sites(entry, field):
    """Distinct sites whose facts mention a field."""
    out = set()
    for src in entry.get("sources", []):
        if field in (src.get("facts") or "").lower():
            out.add(urlparse(src.get("url", "")).netloc.replace("www.", ""))
    return out


def curated_entries():
    """Curated rares that pass the shipping rules, as (npc, name, level, tame, uiMap, coords, drops)."""
    if not os.path.exists(CURATED):
        return []
    zone_ids = {}
    if os.path.exists(ZONES):
        for k, z in json.load(open(ZONES, encoding="utf-8")).items():
            zone_ids[z["name"].lower()] = int(k)
    out = []
    for e in json.load(open(CURATED, encoding="utf-8")):
        if e.get("conflicts") or not e.get("npc"):
            continue
        in_game = e.get("verified") == "in-game"
        if not in_game and (len(sites(e, "id")) < 2 or len(sites(e, "zone")) < 2):
            continue
        ui_map = e.get("uiMap") or zone_ids.get((e.get("zone") or "").lower())
        if not ui_map:
            print(f"skip {e.get('name')}: unknown zone {e.get('zone')}")
            continue
        coords = (e.get("coords") or []) if (sites(e, "coords") or in_game) else []
        drops = [d for d in e.get("drops") or [] if d.get("item")] if sites(e, "drops") else []
        out.append((int(e["npc"]), e["name"], e.get("level") or 0, bool(e.get("tame")), ui_map, coords, drops))
    return out


curated = curated_entries()

lines = [
    "-- Generated by tools/gen_forever.py from wow-raredb. Do not edit.",
    "-- Rare spawns and Forever loot: ForeverChanges (foreverchanges.pro), used with permission.",
    "-- Not covered by RareNet's GPL licence, see NOTICE.",
    "local _, ns = ...",
    "ns.ForeverRares = {",
]
rares = con.execute("select npc_id, name, level, tameable, ui_map_id from rares order by npc_id").fetchall()
for npc, name, level, tame, ui_map in rares:
    coords = con.execute("select x, y from rare_coords where npc_id = ? order by x, y", (npc,)).fetchall()
    flat = ", ".join("%.1f, %.1f" % c for c in coords)
    is_tame = "true" if tame and str(tame).lower() not in ("0", "no", "false", "none") else "false"
    lines.append("  [%d] = { %s, %d, %s, %d, { %s } }," % (npc, lua_string(name), first_int(level), is_tame, ui_map or 0, flat))
known_npcs = {r[0] for r in rares}
for npc, name, level, tame, ui_map, coords, drops in curated:
    if npc in known_npcs:
        continue
    flat = ", ".join("%.1f, %.1f" % (x, y) for x, y in coords)
    lines.append("  [%d] = { %s, %d, %s, %d, { %s } }, -- RareNet research" % (npc, lua_string(name), int(level), "true" if tame else "false", ui_map, flat))
lines.append("}")
lines.append("-- Rares researched by RareNet from public sources (data/curated_rares.json).")
lines.append("ns.CuratedRares = { %s }" % ", ".join("[%d] = true" % c[0] for c in curated if c[0] not in known_npcs))
# Rares known to exist (id confirmed) whose location nobody has published yet.
undiscovered = []
if os.path.exists(CURATED):
    for e in json.load(open(CURATED, encoding="utf-8")):
        if e.get("status") != "undiscovered" or e.get("conflicts") or not e.get("npc"):
            continue
        site_set = {urlparse(s["url"]).netloc.replace("www.", "") for s in e.get("sources", [])}
        if len(site_set) >= 2 and int(e["npc"]) not in known_npcs:
            undiscovered.append(e)
lines.append("-- Rares that exist in Forever but nobody has located yet (RareNet research).")
lines.append("-- npcID = { name, elite, creatureType, likelyTameable }")
lines.append("ns.Undiscovered = {")
for e in sorted(undiscovered, key=lambda x: x["npc"]):
    lines.append("  [%d] = { %s, %s, %s, %s }," % (e["npc"], lua_string(e["name"]), "true" if "elite" in (e.get("rank") or "") else "false",
        lua_string(e.get("type") or ""), "true" if e.get("tame") else "false"))
lines.append("}")
lines.append("ns.ForeverDrops = {")
for (npc,) in con.execute("select distinct npc_id from drops order by npc_id"):
    rows = con.execute("""select d.item_id, coalesce(i.quality, 1) from drops d left join items i on i.item_id = d.item_id
        where d.npc_id = ? order by coalesce(i.quality, 1) desc, d.item_id""", (npc,)).fetchall()
    lines.append("  [%d] = { %s }," % (npc, ", ".join("%d, %d" % r for r in rows)))
for npc, name, level, tame, ui_map, coords, drops in curated:
    if drops and npc not in known_npcs:
        lines.append("  [%d] = { %s }," % (npc, ", ".join("%d, 1" % int(d["item"]) for d in drops)))
lines.append("}")
open(OUT, "w", encoding="utf-8").write("\n".join(lines) + "\n")
print(f"{len(rares)} ForeverChanges rares and {len([c for c in curated if c[0] not in known_npcs])} curated rares written to {OUT}")
