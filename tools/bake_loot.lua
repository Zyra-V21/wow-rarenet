-- Bake community loot into RareNet/ForeverLoot.lua for the next release.
-- Usage: tools/bake_loot.sh <RareNet SavedVariables file>   (writes RareNet/ForeverLoot.lua)
-- The Lua part prints the new file on standard output.
-- Only per-rare totals are written: no player names, no witnesses.
-- A corpse is baked when this client looted it, or when every item in it was
-- reported first hand by at least two different players.
local svPath, outPath = arg[1], arg[2] or "RareNet/ForeverLoot.lua"
assert(svPath, "SavedVariables path required")

local ns = {}
local old = loadfile(outPath)
if old then old("RareNet", ns) end
local loot = ns.ForeverLoot or {}
local corpses = {}
for _, id in ipairs(ns.ForeverLootCorpses or {}) do corpses[id] = true end

dofile(svPath)
local db = RareNetDB or {}
local store = db.drops and db.drops.corpses or {}
local witnesses = db.dropWitnesses or {}

local function players(npc, item)
  local w = witnesses[npc] and witnesses[npc][item]
  local n = 0
  if w then for _ in pairs(w) do n = n + 1 end end
  return n
end

local added = 0
for id, c in pairs(store) do
  if c.npc and not corpses[id] then
    local ok = c.mine
    if not ok then
      ok = next(c.items) ~= nil
      for item in pairs(c.items) do
        if players(c.npc, item) < 2 then ok = false end
      end
    end
    if ok then
      local entry = loot[c.npc] or { 0 }
      loot[c.npc] = entry
      entry[1] = entry[1] + 1
      for item in pairs(c.items) do
        local found = false
        for i = 2, #entry, 2 do
          if entry[i] == item then entry[i + 1] = entry[i + 1] + 1; found = true end
        end
        if not found then entry[#entry + 1] = item; entry[#entry + 1] = 1 end
      end
      corpses[id] = true
      added = added + 1
    end
  end
end

local npcs, ids = {}, {}
for npc in pairs(loot) do npcs[#npcs + 1] = npc end
table.sort(npcs)
for id in pairs(corpses) do ids[#ids + 1] = id end
table.sort(ids)

local out = {
  "-- Generated by tools/bake_loot.lua from loot seen by RareNet players. Do not edit.",
  "-- npcID = { lootedKills, itemID, count, itemID, count, ... }",
  "local _, ns = ...",
  "ns.ForeverLoot = {",
}
for _, npc in ipairs(npcs) do
  local e = loot[npc]
  local parts = {}
  for _, v in ipairs(e) do parts[#parts + 1] = tostring(v) end
  out[#out + 1] = string.format("  [%d] = { %s },", npc, table.concat(parts, ", "))
end
out[#out + 1] = "}"
out[#out + 1] = "-- Corpses already counted above, so gossip does not count them twice."
out[#out + 1] = "ns.ForeverLootCorpses = {"
for i = 1, #ids, 6 do
  local row = {}
  for j = i, math.min(i + 5, #ids) do row[#row + 1] = string.format("%q", ids[j]) end
  out[#out + 1] = "  " .. table.concat(row, ", ") .. ","
end
out[#out + 1] = "}"
out[#out + 1] = string.format("-- baked %d new corpses; %d rares with Forever loot", added, #npcs)
print(table.concat(out, "\n"))
