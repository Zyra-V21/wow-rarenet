#!/usr/bin/env python3
"""Generate RareNet/Seed.lua: rare mobs with name, level, pet family and spawn points.

Spawn points come from wow-copilot's data/npcs.json (QuestieDB Forever, GPL-3.0,
coordinates are [uiMapID, x, y] in 0-100 map percent); pet families from a
vmangos database.
"""
import json
import sqlite3
import sys

NPCS = sys.argv[1] if len(sys.argv) > 1 else "../wow-copilot/data/npcs.json"
DB = sys.argv[2] if len(sys.argv) > 2 else "../wow-copilot/vendor/vmangos/mangos.sqlite"
OUT = "RareNet/Seed.lua"
RARE_RANKS = (2, 4)   # 2 = rare elite, 4 = rare
MERGE = 2.5           # spawn points closer than this (map percent) collapse into one


def families_and_displays():
    con = sqlite3.connect(DB)
    rows = con.execute("select entry, max(pet_family), max(display_id1) from creature_template group by entry")
    fam, disp = {}, {}
    for entry, family, display in rows:
        fam[entry], disp[entry] = family, display
    return fam, disp


def dedupe(points):
    kept = []
    for m, x, y in points:
        if all(m != km or (x - kx) ** 2 + (y - ky) ** 2 > MERGE ** 2 for km, kx, ky in kept):
            kept.append((m, x, y))
    return kept


def lua_string(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


npcs = json.load(open(NPCS, encoding="utf-8"))
fam, disp = families_and_displays()
rows = []
for key, npc in npcs.items():
    if npc.get("elite") not in RARE_RANKS:
        continue
    npc_id = int(key)
    spawns = dedupe([tuple(p) for p in npc.get("at", [])])
    level = npc.get("lvl") or 0
    if isinstance(level, list):
        level = level[0]
    rows.append((npc_id, npc["name"], level, fam.get(npc_id) or 0, disp.get(npc_id) or 0, spawns))
rows.sort()

with open(OUT, "w", encoding="utf-8") as f:
    f.write("-- Generated by tools/gen_seed.py from QuestieDB Forever (GPL-3.0) and vmangos. Do not edit.\n")
    f.write("-- npcID = { name, level, petFamily (0 = not tameable), displayID, { uiMapID, x, y, ... } }\n")
    f.write("local _, ns = ...\nns.Seed = {\n")
    for npc_id, name, level, family, display, spawns in rows:
        flat = ", ".join("%d, %.1f, %.1f" % p for p in spawns)
        f.write("  [%d] = { %s, %d, %d, %d, { %s } },\n" % (npc_id, lua_string(name), level, family, display, flat))
    f.write("}\n")
with_spawns = sum(1 for r in rows if r[5])
print(f"{len(rows)} rares ({with_spawns} with spawn points) written to {OUT}")
