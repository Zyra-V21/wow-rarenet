#!/usr/bin/env python3
"""Generate RareNet/Loot.lua: what each rare in the seed drops (vmangos, GPL).

Per rare, up to MAX_ITEMS items as itemID, chance in tenths of a percent and
quality, best first. References to shared loot groups are expanded when the
rare is likely to drop from them (chance >= REF_MIN); the generic world-drop
pools (low-chance references to hundreds of items) are left out.
"""
import re
import sqlite3
import sys

DB = sys.argv[1] if len(sys.argv) > 1 else "../wow-copilot/vendor/vmangos/mangos.sqlite"
SEED = "RareNet/Seed.lua"
OUT = "RareNet/Loot.lua"
MAX_ITEMS = 12
REF_MIN = 25.0          # percent; references below this are world-drop pools
REF_MAX_ITEMS = 40      # bigger reference pools are generic, skip them
MIN_CHANCE = 0.5        # percent; rarer drops are noise unless green or better

con = sqlite3.connect(DB)
npcs = [int(m) for m in re.findall(r"^\s*\[(\d+)\] = ", open(SEED, encoding="utf-8").read(), re.M)]
quality = dict(con.execute("select entry, max(quality) from item_template group by entry"))


def rows(table, entry):
    return con.execute(f"""select item, max(ChanceOrQuestChance), groupid, max(mincountOrRef)
        from {table} where entry = ? group by item, groupid""", (entry,)).fetchall()


def expand(table, entry, scale, out, depth=0):
    items = rows(table, entry)
    # Items in a group with chance 0 share what is left of the group equally.
    groups = {}
    for item, chance, group, ref in items:
        if group:
            groups.setdefault(group, []).append(chance)
    for item, chance, group, ref in items:
        c = abs(chance)
        if group and c == 0:
            used = sum(abs(x) for x in groups[group] if x)
            zero = sum(1 for x in groups[group] if not x)
            c = max(0.0, 100 - used) / zero
        c = c * scale / 100
        if ref is not None and ref < 0:
            if depth < 2 and c >= REF_MIN * scale / 100:
                if con.execute("select count(*) from reference_loot_template where entry = ?", (-ref,)).fetchone()[0] <= REF_MAX_ITEMS:
                    expand("reference_loot_template", -ref, c, out, depth + 1)
            continue
        out[item] = max(out.get(item, 0), c)


with open(OUT, "w", encoding="utf-8") as f:
    f.write("-- Generated by tools/gen_loot.py from the vmangos database (GPL). Do not edit.\n")
    f.write("-- npcID = { itemID, chance in tenths of a percent, quality, ... } best first\n")
    f.write("local _, ns = ...\nns.Loot = {\n")
    total = 0
    for npc in sorted(npcs):
        lid = con.execute("select max(loot_id) from creature_template where entry = ?", (npc,)).fetchone()[0]
        if not lid:
            continue
        drops = {}
        expand("creature_loot_template", lid, 100.0, drops)
        items = [(i, c, quality.get(i, 1) or 0) for i, c in drops.items()
                 if i in quality and (c >= MIN_CHANCE or (quality.get(i) or 0) >= 2)]
        # Notable first (green or better with a real chance), then by chance.
        items.sort(key=lambda x: (-(x[2] >= 2 and x[1] >= 1), -x[1]))
        items = items[:MAX_ITEMS]
        if not items:
            continue
        flat = ", ".join("%d, %d, %d" % (i, max(1, round(c * 10)), q) for i, c, q in items)
        f.write("  [%d] = { %s },\n" % (npc, flat))
        total += 1
    f.write("}\n")
print(f"loot for {total} rares written to {OUT}")
