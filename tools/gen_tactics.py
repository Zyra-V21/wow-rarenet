#!/usr/bin/env python3
"""Generate RareNet/Tactics.lua: how to find and fight each rare.

Forever comes first: the rank from wow-raredb (ForeverChanges data, used with
their permission) and the tips RareNet wrote from it (data/forever_tips.json).
Then what the classic vmangos database knows, shown as classic data: the
spells the rare casts (its spell list and its scripted casts, some only below
a share of its health), when it flees or calls for help, what it summons, and
its respawn time. Only spell IDs ship; the game client names and describes
them in the player's language.

ns.Tactics = { [npc] = { rank, rankFromForever, tip, { spellID, belowHealth%, ... },
                         flee%, help%, { summoned name, ... }, respawnMin, respawnMax } }
"""
import json
import re
import sqlite3
import sys

VMANGOS = sys.argv[1] if len(sys.argv) > 1 else "../wow-copilot/vendor/vmangos/mangos.sqlite"
RAREDB = sys.argv[2] if len(sys.argv) > 2 else "../wow-raredb/raredb.sqlite"
TIPS = "data/forever_tips.json"
OUT = "RareNet/Tactics.lua"

RANKS = {1: "Elite", 2: "Rare elite", 3: "Boss", 4: "Rare"}
EV_OUT_OF_COMBAT, EV_HEALTH, EV_DEATH, EV_SPAWNED = 1, 2, 6, 11
CMD_SUMMON, CMD_CAST, CMD_FLEE, CMD_HELP = 10, 15, 47, 50


def lua_string(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def rare_ids():
    ids = set()
    for path in ("RareNet/Seed.lua", "RareNet/ForeverRares.lua"):
        ids |= {int(m) for m in re.findall(r"^\s*\[(\d+)\] = \{ \"", open(path, encoding="utf-8").read(), re.M)}
    return sorted(ids)


ATTR_PASSIVE = 0x40
AURA_STEALTH, AURA_SHAPESHIFT = 16, 36


def useless(con, spell):
    """Passive auras, stances, forms and stealth: nothing a player fights against."""
    row = con.execute("select attributes, effectApplyAuraName1, effectApplyAuraName2, effectApplyAuraName3 "
                      "from spell_template where entry = ? limit 1", (spell,)).fetchone()
    if not row:
        return True
    return bool(row[0] & ATTR_PASSIVE) or any(a in (AURA_STEALTH, AURA_SHAPESHIFT) for a in row[1:])


def classic(con, npc):
    """What vmangos knows of a rare: rank, spells, flee/help health, summons, respawn."""
    row = con.execute("select spell_list_id, rank from creature_template where entry = ? order by patch desc limit 1",
                      (npc,)).fetchone()
    if not row:
        return None
    spell_list, rank = row
    spells, flee, help_at, summons = [], 0, 0, []

    def add_spell(spell, below=0):
        if spell and not useless(con, spell) and all(s != spell for s, _ in spells):
            spells.append((spell, below))

    if spell_list:
        entry = con.execute("select * from creature_spells where entry = ?", (spell_list,)).fetchone()
        if entry:
            for k in range(8):
                add_spell(entry[2 + k * 11])
    events = con.execute("select event_type, event_param1, action1_script, action2_script, action3_script "
                         "from creature_ai_events where creature_id = ? order by id", (npc,)).fetchall()
    for ev_type, param1, *scripts in events:
        if ev_type in (EV_OUT_OF_COMBAT, EV_DEATH, EV_SPAWNED):
            continue
        below = param1 if ev_type == EV_HEALTH else 0
        for script in scripts:
            if not script:
                continue
            for cmd, datalong in con.execute("select command, datalong from creature_ai_scripts where id = ?", (script,)):
                if cmd == CMD_CAST:
                    add_spell(datalong, below)
                elif cmd == CMD_FLEE:
                    flee = below or flee
                elif cmd == CMD_HELP:
                    help_at = below or help_at
                elif cmd == CMD_SUMMON:
                    name = con.execute("select name from creature_template where entry = ? limit 1", (datalong,)).fetchone()
                    if name and name[0] not in summons:
                        summons.append(name[0])
    # the respawn most of its spawns share (a rare's spawn rows can mix in
    # odd timers), the longer one on a tie
    respawn = con.execute("select spawntimesecsmin, spawntimesecsmax from creature where id = ? "
                          "group by 1, 2 order by count(*) desc, 1 desc limit 1", (npc,)).fetchone() or (None, None)
    return RANKS.get(rank), spells, flee, help_at, summons, respawn


def forever_ranks():
    con = sqlite3.connect(RAREDB)
    return {npc: (rank or "").capitalize() for npc, rank in con.execute("select npc_id, rank from rares") if rank}


def main():
    con = sqlite3.connect(VMANGOS)
    tips = {int(k): v for k, v in json.load(open(TIPS, encoding="utf-8")).items() if not k.startswith("_")}
    franks = forever_ranks()
    lines = [
        "-- Generated by tools/gen_tactics.py. Do not edit.",
        "-- How to find and fight each rare: Forever first (rank from ForeverChanges data, used with",
        "-- their permission, and RareNet's tips), then classic vmangos data. Spells are IDs only:",
        "-- the client names and describes them.",
        "-- npcID = { rank, rankFromForever, tip, { spellID, belowHealth%, ... }, flee%, help%,",
        "--           { summoned, ... }, respawnMin, respawnMax }",
        "local _, ns = ...",
        "ns.Tactics = {",
    ]
    count = 0
    for npc in rare_ids():
        c = classic(con, npc)
        rank, spells, flee, help_at, summons, respawn = c if c else (None, [], 0, 0, [], (None, None))
        from_forever = npc in franks
        rank = franks.get(npc) or rank
        tip = tips.get(npc)
        if tip and re.search(r"respawn|between spawns|to come back|after a kill", tip, re.I):
            respawn = (None, None)  # Forever's word on the respawn wins over the classic timer
        if not (rank or tip or spells or flee or help_at or summons):
            continue
        flat = ", ".join("%d, %d" % s for s in spells)
        adds = ", ".join(lua_string(s) for s in summons)
        lines.append("  [%d] = { %s, %s, %s, { %s }, %d, %d, { %s }, %d, %d }," % (
            npc, lua_string(rank) if rank else "nil", "true" if from_forever else "false",
            lua_string(tip) if tip else "nil", flat, flee, help_at, adds, respawn[0] or 0, respawn[1] or 0))
        count += 1
    lines += ["}", "return ns.Tactics"]
    open(OUT, "w", encoding="utf-8").write("\n".join(lines) + "\n")
    print("%d rares written to %s (%d tips)" % (count, OUT, len(tips)))


if __name__ == "__main__":
    main()
